package com.example.data.remote.brain

import com.example.data.model.ChatMessage
import java.util.Locale

object ReasoningBrain {

    fun synthesize(
        clean: String,
        lower: String,
        history: List<ChatMessage>
    ): String {
        // Detect question type
        val isHowTo = clean.contains("ဘယ်လို") || clean.contains("နည်းလမ်း") || lower.contains("how to") || lower.contains("how do")
        val isWhy = clean.contains("ဘာကြောင့်") || clean.contains("ဘာဖြစ်လို့") || lower.contains("why")
        val isWhat = clean.contains("ဘာလဲ") || clean.contains("ဆိုတာ") || lower.contains("what is") || lower.contains("what are")
        val isRecommendation = clean.contains("အကြံ") || clean.contains("ကောင်းမလဲ") || lower.contains("recommend") || lower.contains("suggest")
        val isComparison = clean.contains("ကွာခြားချက်") || clean.contains("versus") || clean.contains("vs") || lower.contains("difference")

        // Context awareness from history
        val contextNote = if (history.isNotEmpty()) {
            val lastUser = history.lastOrNull { it.role == ChatMessage.Role.USER }
            if (lastUser != null && lastUser.content != clean) {
                "\n*(ယခင်ဆွေးနွေးချက်: \"${lastUser.content.take(30)}...\" နှင့် ဆက်စပ်ပြီး စိစစ်ထားပါသည်)*\n"
            } else ""
        } else ""

        return when {
            isHowTo -> """
                🤖 **Mr.A Step-by-Step Guide (အဆင့်ဆင့် ဆောင်ရွက်နည်း):**
                $contextNote
                လူကြီးမင်း မေးမြန်းထားသော: **"$clean"** အတွက် အဆင့်ဆင့် လုပ်ဆောင်နိုင်မည့် နည်းလမ်းများ-
                
                1. **အဆင့် (၁) - ပြင်ဆင်ခြင်းနှင့် လေ့လာခြင်း (Preparation):**
                   - အဓိက လိုအပ်ချက်များနှင့် ဦးတည်ချက်ကို ရှင်းလင်းစွာ သတ်မှတ်ပါ။
                   - လိုအပ်သော အထောက်အကူပြု ကိရိယာများကို စုစည်းပါ။
                
                2. **အဆင့် (၂) - လက်တွေ့ အကောင်အထည်ဖော်ခြင်း (Execution):**
                   - အသေးစိတ် အဆင့်များအတိုင်း တစ်ဆင့်ချင်း စနစ်တကျ စတင်ဆောင်ရွက်ပါ။
                   - ဖြစ်ပေါ်လာနိုင်သော အခက်အခဲများကို ကြိုတင်ပြင်ဆင်ထားပါ။
                
                3. **အဆင့် (၃) - စစ်ဆေးသုံးသပ်ခြင်း (Review & Optimization):**
                   - ရရှိလာသော ရလဒ်သည် သတ်မှတ်ထားသော စံနှုန်းနှင့် ကိုက်ညီမှု ရှိမရှိ ပြန်လည်စစ်ဆေးပါ။
                   - ပိုမိုကောင်းမွန်အောင် လိုအပ်သော ပြင်ဆင်မှုများ ပြုလုပ်ပါ။
                
                💡 **အကြံပြုချက်:** မည်သည့်အဆင့်တွင် အခက်အခဲရှိသည်ကို ပြောပြပါက အသေးစိတ် ဆက်လက် ကူညီပေးနိုင်ပါသည်။
            """.trimIndent()

            isWhy -> """
                🤖 **Mr.A Deep Analysis (အကြောင်းရင်း ဆန်းစစ်ချက်):**
                $contextNote
                **မေးခွန်း:** *"$clean"*
                
                ဤကိစ္စရပ် ဖြစ်ပေါ်ရခြင်း၏ အဓိက အကြောင်းရင်းကြီး (၃) ချက်မှာ-
                
                • **အခြေခံ အကြောင်းတရား (Primary Factor):** သဘာဝယုတ္တိ သို့မဟုတ် စနစ်၏ အခြေခံဖွဲ့စည်းပုံကြောင့် ဖြစ်ပေါ်လာခြင်း။
                • **ပတ်ဝန်းကျင်နှင့် ပြင်ပလွှမ်းမိုးမှု (External Influence):** ဆက်စပ်နေသော အခြားအခြေအနေများနှင့် တုံ့ပြန်မှုများ။
                • **ရေရှည် သက်ရောက်မှု (Long-term Impact):** ဤအကြောင်းရင်းကို နားလည်ထားခြင်းဖြင့် နောင်တွင် ကြိုတင်စီမံ ကာကွယ်နိုင်ခြင်း။
                
                နောက်ထပ် မည်သည့်အချက်ကို အကျယ်တဝံ့ ဆွေးနွေးလိုပါသလဲခင်ဗျာ?
            """.trimIndent()

            isWhat -> """
                🤖 **Mr.A Knowledge Explainer (ရှင်းလင်းချက်):**
                $contextNote
                **အကြောင်းအရာ:** **"$clean"**
                
                📌 **အဓိပ္ပာယ် ဖွင့်ဆိုချက် (Core Definition):**
                မေးမြန်းထားသော ကိစ္စရပ်သည် လူကြီးမင်း သိရှိလိုသော နယ်ပယ်တွင် အရေးပါသော အခြေခံ သဘောတရားတစ်ခု ဖြစ်ပါသည်။
                
                🔍 **အဓိက ပါဝင်သော အချက်များ:**
                - **သဘောသဘာဝ:** ၎င်း၏ လုပ်ဆောင်ပုံနှင့် အသုံးဝင်မှု။
                - **လက်တွေ့ အသုံးချမှု:** လူမှုဘဝ သို့မဟုတ် လုပ်ငန်းခွင်တွင် အကျိုးသက်ရောက်ပုံ။
                - **အကျိုးကျေးဇူး:** မှန်ကန်စွာ သိရှိနားလည်ခြင်းဖြင့် ရရှိနိုင်သော အကျိုးရလဒ်များ။
                
                လိုအပ်ပါက နမူနာများဖြင့် ထပ်မံရှင်းပြပေးနိုင်ပါသည်ခင်ဗျာ။
            """.trimIndent()

            isComparison -> """
                🤖 **Mr.A Comparative Analysis (နှိုင်းယှဉ်ချက်):**
                $contextNote
                **နှိုင်းယှဉ်မည့် အကြောင်းအရာ:** *"$clean"*
                
                ⚖️ **ဘက်စုံ နှိုင်းယှဉ်ချက် သုံးသပ်ချက်:**
                
                | အချက်အလက် | ပထမ ရွေးချယ်မှု | ဒုတိယ ရွေးချယ်မှု |
                | :--- | :--- | :--- |
                | **အားသာချက်** | ပိုမိုမြန်ဆန်/လွယ်ကူခြင်း | စွမ်းဆောင်ရည် ပိုမိုမြင့်မားခြင်း |
                | **အသုံးပြုသင့်သည့် အခြေအနေ** | စတင်လေ့လာသူများအတွက် | ကျွမ်းကျင်သူ/လုပ်ငန်းခွင်သုံးအတွက် |
                | **ကုန်ကျစရိတ်/အချိန်** | သက်သာမှုရှိခြင်း | အနည်းငယ် အချိန်ပေးရခြင်း |
                
                💡 **Mr.A ၏ အကြံပြုချက်:** သင်၏ အဓိက လိုအပ်ချက်နှင့် ဘတ်ဂျက်/အချိန်ပေါ် မူတည်၍ သင့်တော်ရာကို ရွေးချယ်သင့်ပါသည်။
            """.trimIndent()

            isRecommendation -> """
                🤖 **Mr.A Recommendations (အကြံပြုချက်များ):**
                $contextNote
                **တောင်းဆိုချက်:** *"$clean"*
                
                အကောင်းဆုံး အကြံပြုလိုသည့် နည်းလမ်းများမှာ:
                
                1. **အကောင်းဆုံး ရွေးချယ်မှု (Best Pick):** လက်ရှိ အခြေအနေတွင် အသုံးဝင်ဆုံးနှင့် စိတ်အချရဆုံး နည်းလမ်းကို ရွေးချယ်ပါ။
                2. **အရန် နည်းလမ်း (Alternative):** ပထမနည်းလမ်း အဆင်မပြေပါက ဒုတိယ အရန်အစီအစဉ်ကို ကြိုတင်ထားရှိပါ။
                3. **သတိပြုရမည့် အချက်:** မလိုအပ်သော စွန့်စားမှုများနှင့် အချိန်ကုန်ဆုံးမှုများကို ရှောင်ကြဉ်ပါ။
                
                ဆက်လက်၍ မည်သည့်အချက်ကို အသေးစိတ် စဉ်းစားလိုပါသလဲခင်ဗျာ?
            """.trimIndent()

            else -> """
                🤖 **Mr.A Personal Assistant:**
                $contextNote
                လူကြီးမင်း မေးမြန်းထားသော: *"$clean"*
                
                ကျွန်တော် Mr.A သည် လူကြီးမင်း၏ မေးခွန်းကို အလေးထား စိစစ်ပြီး အောက်ပါ အချက်များဖြင့် ကူညီအကြံပြု ပေးပါသည်-
                
                • **အဓိက အချက်:** မေးခွန်းနှင့် သက်ဆိုင်သော အခြေခံအချက်များကို စနစ်တကျ ချဉ်းကပ်ဆောင်ရွက်နိုင်ပါသည်။
                • **ကူညီနိုင်သော ကဏ္ဍများ:** အသေးစိတ် ရှင်းလင်းချက်များ၊ တွက်ချက်မှုများ၊ စာရေးသားခြင်းနှင့် နည်းပညာ အထောက်အကူများကို ဆက်လက် တောင်းဆိုနိုင်ပါသည်။
                • **လွတ်လပ်စွာ မေးမြန်းနိုင်ခြင်း:** သင်သိလိုသော မည်သည့် အကြောင်းအရာကိုမဆို ဆက်လက် မေးမြန်းနိုင်ပါသည်ခင်ဗျာ။
            """.trimIndent()
        }
    }
}
